logger = logging.getLogger(__name__)

FIRST_LINE_IN_FILE = "# This file was generated by dbttestenv.model_generator"
_ACCEPTED_FIRST_LINES = [
    FIRST_LINE_IN_FILE,
    # Legacy header written by old project-local model_generator
    "# This file was generated by dbt/unit_tests/models/model_generator.py",
]


def read_config_yml(file_path: Path) -> dict[str, Any]:
    """Read the code generation configuration from a YAML file."""
    with file_path.open("r", encoding="utf-8") as f:
        config = safe_load(f)
    if not isinstance(config, dict):
        raise ValueError(f"Invalid configuration format in {file_path}")
    return config


def alter_add_primary_key(connection: Connection, table: Table):
    """Alter the table to add a primary key column if it does not exist."""
    ensure_primary_key(table)
    connection.execute(
        text(
            f"ALTER TABLE {table.schema}.{table.name} ADD pk_dummy NUMBER(38, 0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    )


def basic_copy_column(col: Column, primary_key: bool = None) -> Column:
    """Create a copy of a column, taking into account only the attributes needed for basic model generation.

    Overrides the primary key if specified, otherwise keeps the original value.

    """
    return Column(
        col.name,
        col.type,
        primary_key=col.primary_key if primary_key is None else primary_key,
        nullable=col.nullable,
        autoincrement=col.autoincrement
    )


def drop_extra_columns(table: Table, required_columns: list[str] | None) -> Table:
    """If specified, replace the table with one that only has the required columns ."""
    if not required_columns:
        return table

    existing = {col for col in table.columns.keys()}
    required_columns = set(required_columns)

    specified_but_missing = required_columns - existing
    if specified_but_missing:
        cols_str = ", ".join(specified_but_missing)
        raise ValueError(f"Columns '{cols_str}' specified in config but not found in table {table.name}")

    new_columns = [
        basic_copy_column(c)
        for c in table.columns
        if c.name in required_columns or c.name == "pk_dummy"
    ]
    metadata = table.metadata
    metadata.remove(table)
    return Table(
        table.name,
        metadata,
        *new_columns,
        extend_existing=False,
        schema=table.schema
    )


def apply_configured_primary_keys(metadata: MetaData, objects: list[dict[str, Any]]):
    obj_config_by_name = {cfg["name"]: cfg for cfg in objects}
    for table in metadata.sorted_tables:
        if table.name not in obj_config_by_name:
            continue

        config = obj_config_by_name[table.name]
        if "unique" not in config:
            raise ValueError(f"Configuration for table {table.name} does not contain 'unique' key.")

        pk_columns = config["unique"]
        if not isinstance(pk_columns, list):
            raise ValueError(f"Primary key for table {table.name} must be a list of column names.")
        if not pk_columns:
            raise ValueError(f"Primary key for table {table.name} cannot be empty.")

        for col_name in pk_columns:
            if col_name not in table.columns:
                raise ValueError(f"Primary key column '{col_name}' not found in table {table.name}")

            table.append_column(
                basic_copy_column(table.columns[col_name], primary_key=True),
                replace_existing=True
            )


def reflect(bind: Engine | Connection, schema: str, objects: list[dict[str, str]]) -> MetaData:
    metadata = MetaData(schema=schema)
    obj_config_by_name = {cfg["name"]: cfg for cfg in objects}
    metadata.reflect(bind, schema=schema, views=True, only=list(obj_config_by_name.keys()))

    for table in metadata.sorted_tables:
        drop_extra_columns(table, obj_config_by_name[table.name].get("columns"))

    return metadata


def write_model_file(file_path: Path, schema: MetaData, engine: Engine):
    """Generate model code and write it to a file for a single schema."""
    file_path.parent.mkdir(parents=True, exist_ok=True)
    with file_path.open("w", encoding="utf-8") as f:
        f.write(FIRST_LINE_IN_FILE + "\n")
        f.write("# Do not edit this file directly.\n\n")

        generator = DeclarativeGenerator(schema, engine, options=["nocomments", "noconstraints", "noindexes"])
        f.write(generator.generate())

        logger.info(f"Wrote {len(schema.tables)} objects from schema '{schema.schema}' to '{file_path}'")


@dataclass
class ReflectedModels:
    """Container for reflected models."""
    dbt_schema: MetaData
    sources: list[MetaData]


def reflect_models(engine: Engine, config: dict[str, Any], models: list | None) -> ReflectedModels:
    """Reflect the configured schemas and generate code defining SQLAlchemy models.

    Args:
        engine (Engine): The SQLAlchemy engine to use for reflection.
        config (dict): The configuration dictionary.
        models (list | None): Optional list of qualified model names to include (format: 'schema.object').
                             If None, all models are included.
    """

    # Apply filter if present to update sqlalchemy models selectively
    dbt_models = config["dbt_schema"]["dbt_models"]
    dbt_schema_name = config["dbt_schema"]["name"]
    sources_config = []
    if models:
        logger.info(f"Filtering to specified models: {', '.join(models)}")
        dbt_models = [m for m in dbt_models if f"{dbt_schema_name}.{m['name']}" in models]
        match_count = len(dbt_models)
        for source in config["sources"]:
            modified_source = source.copy()
            modified_source["objects"] = [
                m for m in source["objects"] if f"{source['schema']}.{m['name']}" in models
            ]
            if modified_source["objects"]:
                sources_config.append(modified_source)
                match_count += len(modified_source["objects"])

        if match_count == 0:
            raise ValueError("The specified filter did not match any models.")
        elif match_count < len(models):
            raise ValueError(f"The specified filter matched only {match_count}/{len(models)} models.")
    else:
        sources_config = config["sources"]

    # Reflect the dbt schema
    logger.info(f"Reading dbt schema '{dbt_schema_name}'")
    dbt_schema = reflect(engine, dbt_schema_name, dbt_models)

    # sqlalchemy requires primary keys for declarative models
    apply_configured_primary_keys(dbt_schema, dbt_models)

    # Reflect all schemas containing sources
    sources: list[MetaData] = []
    for source_config in sources_config:
        logger.info(f"Reading source schema '{source_config['schema']}'")
        sources_metadata = reflect(engine, source_config["schema"], source_config["objects"])
        for table in sources_metadata.sorted_tables:
            ensure_primary_key(table)

        sources.append(sources_metadata)

    return ReflectedModels(dbt_schema=dbt_schema, sources=sources)


def write_models(engine: Engine, reflected_models: ReflectedModels, output_dir: Path):
    """Write to disk using sqlalacodegen"""
    # Generate code for the dbt schema
    output_file = output_dir / "dbt_models.py"
    write_model_file(output_file, reflected_models.dbt_schema, engine)
    (output_dir / "__init__.py").touch()

    # Generate code for each source schema
    sources_dir = output_dir / "sources"
    for source_schema in reflected_models.sources:
        output_file = sources_dir / f"{source_schema.schema}.py"
        write_model_file(output_file, source_schema, engine)

    (sources_dir / "__init__.py").touch()


def delete_output_dir(output_dir: Path):
    """Delete the output directory if it exists.

    Check if the directory contains nothing but generated files."""
    if not output_dir.exists():
        return

    if not output_dir.is_dir():
        raise ValueError(f"Output path {output_dir} is not a directory.")

    # All files in the output directory or its subdirectories
    all_files = list(f for f in output_dir.rglob("*") if f.is_file())

    # Abort if any of the files is not a python file
    if not all(f.suffix in [".py", ".pyc"] for f in all_files):
        raise ValueError(f"Output directory {output_dir} contains non-Python files, cannot delete.")

    # Abort if any of the files does not start with FIRST_LINE_IN_FILE
    for f in all_files:
        if f.suffix == ".pyc":
            # Skip compiled Python files
            continue

        with f.open("r", encoding="utf-8") as file:
            # Skip __init__.py files, they are allowed to be empty
            if f.name == "__init__.py":
                if file.read().strip() != "":
                    raise ValueError(
                        f"Output directory {output_dir} contains non-generated __init__.py, cannot delete."
                    )
                continue

            first_line = file.readline().strip()
            if first_line not in _ACCEPTED_FIRST_LINES:
                raise ValueError(f"Output directory {output_dir} contains non-generated files, cannot delete.")

    # Delete the directory contents
    logger.info(f"Deleting existing files in {output_dir}")
    for item in output_dir.iterdir():
        if item.is_dir():
            rmtree(item)
        else:
            item.unlink()


def import_module_from_path(module_path: Path):
    """Import a module from a given file path."""
    import importlib.util

    if not module_path.exists() or not module_path.is_file():
        raise ValueError(f"Module path {module_path} does not exist or is not a file.")

    spec = importlib.util.spec_from_file_location(module_path.stem, module_path)
    if spec is None:
        raise ImportError(f"Could not load module from {module_path}")

    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def merge_tables_from_module(module: Any, metadata: MetaData):
    """Merge all tables from a module into the provided metadata."""
    if not hasattr(module, "Base") or not hasattr(module.Base, "metadata"):
        raise ValueError(f"Module {module} does not have a Base with metadata.")

    for table in module.Base.metadata.sorted_tables:
        table.to_metadata(metadata)


def collect(output_dir: Path, dbt_models: bool = False) -> MetaData:
    """Collect all Python files in the output directory in a single context"""
    if not output_dir.exists() or not output_dir.is_dir():
        raise ValueError(f"Output path {output_dir} is not a directory.")

    metadata = MetaData()

    if dbt_models:
        logger.debug(f"Collecting DBT models from {output_dir}")
        dbt_models = import_module_from_path(output_dir / "dbt_models.py")
        merge_tables_from_module(dbt_models, metadata)

    for source_file in output_dir.rglob("sources/*.py"):
        if source_file.name == "__init__.py":
            continue
        logger.debug(f"Collecting source models from {source_file}")
        source_module = import_module_from_path(source_file)
        merge_tables_from_module(source_module, metadata)

    return metadata


@dataclass(frozen=True)
class FilterSpec:
    schema: str
    table: str | None

    def match(self, table: Table) -> bool:
        """Check if the table matches the filter specification."""
        if self.table:
            return table.schema == self.schema and table.name == self.table
        return table.schema == self.schema

    @classmethod
    def from_string(cls, filter_pattern: str) -> 'FilterSpec':
        """Create a FilterSpec from a string pattern."""
        parts = filter_pattern.split('.')
        if len(parts) == 1:
            return cls(schema=parts[0], table=None)
        elif len(parts) == 2:
            return cls(schema=parts[0], table=parts[1])
        else:
            raise ValueError(f"Invalid filter pattern: {filter_pattern}")

    def __str__(self):
        return f"{self.schema}.{self.table}" if self.table else self.schema


def filter_metadata(metadata: MetaData, filter_patterns: list[str] | None) -> MetaData:
    """Filter metadata tables based on a pattern (schema or schema.table)"""
    if not filter_patterns:
        return metadata

    filter_specs = [FilterSpec.from_string(pattern) for pattern in filter_patterns]

    # make sure there are no conflicts (schema wildcard + specific table in the same schema)
    specs_by_schema = dict()
    for schema, spec_group in itertools.groupby(filter_specs, key=lambda spec: spec.schema):
        specs = list(set(spec_group))
        specs_by_schema[schema] = specs
        if len(specs) > 1 and any(spec.table is None for spec in specs):
            raise ValueError(
                f"Conflicting filter patterns for schema '{schema}': {', '.join(str(spec) for spec in specs)}")

    filtered_metadata = MetaData()
    for table in metadata.tables.values():
        for spec in specs_by_schema.get(table.schema, []):
            if spec.match(table):
                table.to_metadata(filtered_metadata)
                break

    return filtered_metadata


def create_missing(connection: Connection, metadata: MetaData):
    """Create missing models. Logs progress, opposed to sqlalachemy's `create_all`"""
    current_db = sqlalchemy.inspect(connection)
    for table in metadata.sorted_tables:
        if not current_db.has_table(table.name, schema=table.schema):
            connection.execute(CreateTable(table))
            logger.info(f"Created table {table.name} in schema {table.schema}")
        else:
            logger.warning(f"Table {table.name} already exists in schema {table.schema}, skipping creation.")


def cli():
    parser = argparse.ArgumentParser(description="Generate SQLAlchemy models from Oracle DB schema.")

    command_parser = parser.add_subparsers(dest="command", required=True)

    def default_command_args(parser: argparse.ArgumentParser):
        parser.add_argument("--config", type=Path, help="Path to config YAML file", default=None)
        parser.add_argument("--user", help="Database username")
        parser.add_argument("--host", help="Database host")
        parser.add_argument("--port", help="Database port")
        parser.add_argument("--service-name", help="Oracle service name")
        parser.add_argument("--output-dir", help="Output directory for generated models", type=Path,
                            default=Path.cwd() / "generated")
        parser.add_argument("--testcontainer", action="store_true", default=False,
                            help="Connect to local testcontainer instead of specifying connection explicitly")

    generate_cmd = command_parser.add_parser("generate", help="Generate SQLAlchemy models from Oracle DB schema.")
    generate_cmd.add_argument("--no-delete", help="Do not delete existing files in output directory", default=False,
                              action="store_true")
    generate_cmd.add_argument("--models", nargs="+", default=None,
                              help="A list of qualified db objects to include (format: 'schema.object'). Implies --no-delete.")
    default_command_args(generate_cmd)

    apply_cmd = command_parser.add_parser("apply", help="Apply models to the database by creating tables")
    apply_cmd.add_argument("--filter", help="Filter models by name (format: 'schema' or 'schema.model')",
                           action="append", default=None)
    apply_cmd.add_argument("--apply-dbt-models", help="Also create models managed by DBT", action="store_true",
                           default=False)
    default_command_args(apply_cmd)

    return parser.parse_args()


def main():
    args = cli()

    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s - %(levelname)s - %(message)s",
        handlers=[
            logging.StreamHandler()
        ]
    )

    codegen_config_path = args.config
    if codegen_config_path is None:
        # If the config path not specified use model_generation.yml in this directory
        codegen_config_path = Path.cwd() / "model_generation.yml"

    if not codegen_config_path.exists():
        raise FileNotFoundError(f"Configuration file not found: {codegen_config_path}")

    logger.info(f"Using configuration file: {codegen_config_path}")
    config = read_config_yml(codegen_config_path)

    if args.testcontainer:
        conn_cfg = get_connection_config()
        if any([args.user, args.host, args.port, args.service_name]):
            raise ValueError("Cannot specify connection parameters when using --testcontainer.")
    else:
        if not all([args.user, args.host, args.port, args.service_name]):
            raise ValueError(
                "Must specify --user, --host, --port and --service-name unless --testcontainer is used.")
        conn_cfg = ConnectionConfig(
            host=args.host,
            port=int(args.port),
            service_name=args.service_name,
            user=args.user,
            password=getpass(f"Enter password for {args.user}: ")
        )

    logger.info(f"Connecting to database {conn_cfg.host}:{conn_cfg.port}@{conn_cfg.service_name} as '{conn_cfg.user}'")
    engine = create_engine(conn_cfg.connection_url)

    # Check which command was specified
    if args.command == 'generate':
        if not args.no_delete and args.models is None:
            delete_output_dir(args.output_dir)

        logger.info(f"Reading SQL definitions from database")
        models = reflect_models(engine, config, args.models)

        logger.info(f"Writing python model definitions to {args.output_dir}")
        write_models(engine, models, args.output_dir)
    elif args.command == 'apply':

        if not args.apply_dbt_models:
            logger.info("Skipping DBT models, only applying source models.")

        metadata = collect(args.output_dir, args.apply_dbt_models)
        collected_count = len(metadata.tables)

        metadata = filter_metadata(metadata, args.filter)
        filtered_count = len(metadata.tables)

        if collected_count != filtered_count:
            logger.info(f"Filters in effect, keeping  {filtered_count}/{collected_count} models.")

        logger.info("Creating models in the database")
        with engine.connect() as connection:
            create_missing(connection, metadata)

    else:
        logger.error(f"Unknown command: {args.command}.")
        return


if __name__ == "__main__":
    main()
